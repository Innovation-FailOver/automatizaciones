const OrbitAnimation = () => {
    const orbits = [120, 180, 240];
    const iconsPerOrbit = [3, 4, 3];

    let iconIndex = 0;

    return (
        <div className="relative w-full max-w-lg aspect-square flex items-center justify-center">
            {/* núcleo */}
            <div className="w-28 h-28 rounded-full bg-gradient-to-r from-indigo-500 to-purple-600 flex items-center justify-center shadow-2xl z-10">
                <Globe className="w-12 h-12 text-white" />
            </div>

            {/* órbitas */}
            {orbits.map((radius, orbitIdx) => (
                <div
                    key={orbitIdx}
                    className="absolute rounded-full border border-gray-300"
                    style={{
                        width: radius * 2,
                        height: radius * 2,
                        top: `calc(50% - ${radius}px)`,
                        left: `calc(50% - ${radius}px)`,
                    }}
                />
            ))}

            {/* íconos */}
            {orbits.map((radius, orbitIdx) => {
                const count = iconsPerOrbit[orbitIdx];
                const angleStep = 360 / count;

                return Array.from({ length: count }).map((_, i) => {
                    if (iconIndex >= icons.length) return null;
                    const icon = icons[iconIndex];
                    iconIndex++;

                    const duration = 12 + orbitIdx * 3;
                    const randomOffset = Math.random() * angleStep;
                    const initialAngle = i * angleStep + randomOffset;

                    return (
                        <motion.div
                            key={icon.name}
                            className="absolute"
                            style={{
                                width: radius * 2,
                                height: radius * 2,
                                top: `calc(50% - ${radius}px)`,
                                left: `calc(50% - ${radius}px)`,
                            }}
                            initial={{ rotate: initialAngle }}
                            animate={{ rotate: 360 + initialAngle }}
                            transition={{ repeat: Infinity, duration, ease: "linear" }}
                        >
                            <div
                                className="absolute top-0 left-1/2 -translate-x-1/2 -translate-y-1/2"
                                style={{ transformOrigin: `center ${radius}px` }}
                            >
                                <div className="w-14 h-14 bg-white rounded-full shadow-lg flex items-center justify-center">
                                    {icon.svg}
                                </div>
                            </div>
                        </motion.div>
                    );
                });
            })}
        </div>
    );
};

export default OrbitAnimation;